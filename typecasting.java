import java.util.*;
public class typecasting {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        float a = 21.5f;
        int b = (int) a;
        System.out.println(b);
        float marks = 99.99f;
        int marks2 = (int) marks;
        System.out.println(marks2);
    }
    
}
